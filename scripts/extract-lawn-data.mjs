import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "kindworks_little_bakery_v65_house_rescue_reintegrated_fixed.html");
const outputPath = path.join(root, "src/data/lawnCareData.js");
const source = await readFile(sourcePath, "utf8");
const mapMatch = source.match(/const EMBEDDED_MINI_GAME_HTML_B64=Object\.freeze\(\{([\s\S]*?)\}\);\s*const EMBEDDED_BEACH/);
if (!mapMatch) throw new Error("The protected embedded mini-game map was not found.");
const payloads = Function(`"use strict"; return ({${mapMatch[1]}});`)();
const payload = Buffer.from(payloads["lawn-care"], "base64").toString("utf8");

const levelsStart = payload.indexOf("const RAW_LEVELS=") + "const RAW_LEVELS=".length;
const levelsEnd = payload.indexOf("\nconst DIRS=", levelsStart);
if (levelsStart < "const RAW_LEVELS=".length || levelsEnd < levelsStart) {
  throw new Error("RAW_LEVELS was not found in the protected Lawn Care payload.");
}
const levels = JSON.parse(payload.slice(levelsStart, levelsEnd));
if (levels.length !== 750) throw new Error(`Expected 750 Lawn Care levels, found ${levels.length}.`);
if (levels.some((level, index) => level.id !== index + 1 || !Array.isArray(level.rows) || !/^[UDLR]+$/.test(level.solution))) {
  throw new Error("The extracted Lawn Care catalogue is incomplete.");
}

const sourceHash = createHash("sha256").update(source).digest("hex");
const payloadHash = createHash("sha256").update(payload).digest("hex");
const moduleSource = `// Generated by scripts/extract-lawn-data.mjs from the protected Kindworks HTML.\n// Do not hand-edit the authored lawns or certified routes.\nexport const LAWN_SOURCE_SHA256 = ${JSON.stringify(sourceHash)};\nexport const LAWN_PAYLOAD_SHA256 = ${JSON.stringify(payloadHash)};\nexport const LAWN_ENGINE_VERSION = "11.0.0-pixel-garden-rebuild";\nexport const LAWN_TOTAL_LEVELS = 750;\nexport const LAWN_CAMPAIGN_QA = Object.freeze(${JSON.stringify({
  version: "v54-release-family-unique",
  minimumOptimalMoves: 9,
  maximumOptimalMoves: 25,
  adjacentStructuralDifferenceMin: 0.3333,
  adjacentStructuralDifferenceMax: 0.5694,
  sourceFamilyCount: 750,
})});\nexport const LAWN_LEVELS = Object.freeze(${JSON.stringify(levels)}.map((level) => Object.freeze({ ...level, rows: Object.freeze(level.rows), metrics: Object.freeze(level.metrics), qa: Object.freeze(level.qa) })));\n`;
await writeFile(outputPath, moduleSource);
console.log(`Extracted 750 Lawn Care levels to ${outputPath}`);
console.log(`Protected source SHA-256: ${sourceHash}`);
console.log(`Lawn payload SHA-256: ${payloadHash}`);
