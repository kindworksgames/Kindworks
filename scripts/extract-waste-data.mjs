import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "kindworks_little_bakery_v65_house_rescue_reintegrated_fixed.html");
const outputPath = path.join(root, "src/data/wasteCollectionData.js");
const source = await readFile(sourcePath, "utf8");
const mapMatch = source.match(/const EMBEDDED_MINI_GAME_HTML_B64=Object\.freeze\(\{([\s\S]*?)\}\);\s*const EMBEDDED_BEACH/);
if (!mapMatch) throw new Error("The protected embedded mini-game map was not found.");
const payloads = Function(`"use strict"; return ({${mapMatch[1]}});`)();
const payload = Buffer.from(payloads["waste-collection"], "base64").toString("utf8");

function jsonConstant(pattern, label) {
  const match = payload.match(pattern);
  if (!match) throw new Error(`${label} was not found in the protected Waste Collection payload.`);
  return JSON.parse(match[1]);
}

const catalog = jsonConstant(/const RUBBISH_CATALOG = (\[[^\n]+\]);/, "RUBBISH_CATALOG")
  .map(({ key, label, fallback }) => ({ key, label, icon: fallback }));
const checkpoints = jsonConstant(/const CHECKPOINT_LEVELS = (\[[^\n]+\]);/, "CHECKPOINT_LEVELS");
const sourceLevels = jsonConstant(/const PHASE13_SOURCE_LEVELS = Object\.freeze\((\[[^\n]+\])\);/, "PHASE13_SOURCE_LEVELS");
const levelData = jsonConstant(/const LEVEL_DATA = (\{[^\n]+\});/, "LEVEL_DATA");
const solutions = jsonConstant(/const PREBUILT_SOLUTIONS = Object\.freeze\((\{[^\n]+\})\);/, "PREBUILT_SOLUTIONS");
if (catalog.length !== 40 || Object.keys(levelData).length !== 750 || Object.keys(solutions).length !== 750) {
  throw new Error("The extracted Waste Collection catalogue is incomplete.");
}

const sourceHash = createHash("sha256").update(source).digest("hex");
const payloadHash = createHash("sha256").update(payload).digest("hex");
const moduleSource = `// Generated by scripts/extract-waste-data.mjs from the protected Kindworks HTML.\n// Do not hand-edit the authored boards or certified solutions.\nexport const WASTE_SOURCE_SHA256 = ${JSON.stringify(sourceHash)};\nexport const WASTE_PAYLOAD_SHA256 = ${JSON.stringify(payloadHash)};\nexport const WASTE_BUILD_VERSION = "72.0.1-phase19-embedded-landscape";\nexport const WASTE_TOTAL_LEVELS = 750;\nexport const WASTE_TILE_STRIDE = 5;\nexport const WASTE_WORLD = Object.freeze({ width: 1080, height: 840, cardWidth: 88, cardHeight: 100 });\nexport const WASTE_TRAY_LIMIT = 5;\nexport const WASTE_CHECKPOINT_LEVELS = Object.freeze(${JSON.stringify(checkpoints)});\nexport const WASTE_SOURCE_LEVELS = Object.freeze(${JSON.stringify(sourceLevels)});\nexport const WASTE_RUBBISH_CATALOG = Object.freeze(${JSON.stringify(catalog)}.map((item) => Object.freeze(item)));\nexport const WASTE_LEVEL_DATA = Object.freeze(${JSON.stringify(levelData)});\nexport const WASTE_CERTIFIED_SOLUTIONS = Object.freeze(${JSON.stringify(solutions)});\n`;
await writeFile(outputPath, moduleSource);
console.log(`Extracted 750 Waste Collection boards and solutions to ${outputPath}`);
console.log(`Protected source SHA-256: ${sourceHash}`);
console.log(`Waste payload SHA-256: ${payloadHash}`);
